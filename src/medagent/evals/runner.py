"""Run a rubric evaluation: load inputs, collect answers, grade and score them.

One *configuration* is one set of answers to the dataset: a pre-recorded
responses file (``label=path``, for example answers recorded from GPT-6.2 Sol
or Claude Opus 5.5) or answers generated by medagent's offline pipeline
(:mod:`medagent.evals.generate`). Every configuration is graded by the same
deterministic rule grader and scored with the same bootstrap seed, so the
results are directly comparable and reproducible.
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import TYPE_CHECKING

from medagent.evals.dataset import RubricDataset, load_responses
from medagent.evals.scoring import (
    DEFAULT_BOOTSTRAP_SAMPLES,
    DEFAULT_CONFIDENCE,
    DEFAULT_SEED,
    MAX_BOOTSTRAP_SAMPLES,
    ConfigResult,
    score_configuration,
)

if TYPE_CHECKING:
    from medagent.agent.state_machine import ClinicalAgentStateMachine

LABEL_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")
MAX_CONFIGURATIONS = 20
RULE_GRADER = "rule"


class EvalConfigError(ValueError):
    """An evaluation was requested with invalid labels, sources or bootstrap settings."""


@dataclass(frozen=True)
class ResponseSource:
    """A pre-recorded responses file and the label it is reported under."""

    label: str
    path: Path


def parse_response_source(spec: str) -> ResponseSource:
    """Parse ``label=path`` (or a bare ``path``, labelled by its file stem).

    Args:
        spec: Command-line value such as ``careful=answers/careful.jsonl``.

    Returns:
        The parsed source.

    Raises:
        EvalConfigError: Empty path or a label that is not 1-64 characters of
            letters, digits, ``.``, ``_`` or ``-``.
    """
    label, sep, path = spec.partition("=")
    if not sep:
        label, path = Path(spec).stem, spec
    if not path:
        raise EvalConfigError(f"responses source {spec!r} has no path")
    if not LABEL_PATTERN.match(label):
        raise EvalConfigError(
            f"configuration label {label!r} must be 1-64 letters, digits, '.', '_' or '-'"
        )
    return ResponseSource(label=label, path=Path(path))


@dataclass(frozen=True)
class EvalRun:
    """Everything a report needs: the dataset, settings and per-configuration results."""

    dataset: RubricDataset
    configurations: tuple[ConfigResult, ...]
    bootstrap_samples: int
    seed: int
    confidence: float
    generated_at: datetime
    grader: str = RULE_GRADER
    generated_responses: Mapping[str, Mapping[str, str]] | None = None


def _check_labels(labels: Sequence[str]) -> None:
    if not labels:
        raise EvalConfigError("nothing to evaluate: pass --responses and/or --generate-offline")
    if len(labels) > MAX_CONFIGURATIONS:
        raise EvalConfigError(f"at most {MAX_CONFIGURATIONS} configurations per run")
    duplicates = sorted({label for label in labels if labels.count(label) > 1})
    if duplicates:
        raise EvalConfigError(f"duplicate configuration label(s): {', '.join(duplicates)}")


async def run_evaluation(
    dataset: RubricDataset,
    sources: Sequence[ResponseSource] = (),
    *,
    generate_offline: bool = False,
    offline_label: str | None = None,
    agent: ClinicalAgentStateMachine | None = None,
    bootstrap_samples: int = DEFAULT_BOOTSTRAP_SAMPLES,
    seed: int = DEFAULT_SEED,
    confidence: float = DEFAULT_CONFIDENCE,
) -> EvalRun:
    """Grade and score every configuration against ``dataset``.

    Args:
        dataset: The validated rubric dataset.
        sources: Pre-recorded responses files, graded in the given order.
        generate_offline: Also answer the dataset with medagent's offline
            pipeline (reported last, as ``offline_label``).
        offline_label: Label of the generated configuration; defaults to
            ``medagent-offline``.
        agent: State machine for generation; ``None`` builds the offline one.
        bootstrap_samples: Bootstrap resamples per aggregate (0 disables the CI).
        seed: Bootstrap seed shared by every configuration.
        confidence: Two-sided confidence level of the bootstrap interval.

    Returns:
        The evaluation run.

    Raises:
        EvalConfigError: No configuration, duplicate or invalid labels, or
            bootstrap settings out of range (including a negative seed).
        RubricDatasetError: A responses file is unreadable or invalid.
    """
    from medagent.evals.generate import OFFLINE_LABEL, OFFLINE_SOURCE, generate_responses

    label = offline_label or OFFLINE_LABEL
    if generate_offline and not LABEL_PATTERN.match(label):
        raise EvalConfigError(f"configuration label {label!r} is invalid")
    _check_labels([source.label for source in sources] + ([label] if generate_offline else []))
    if not 0 <= bootstrap_samples <= MAX_BOOTSTRAP_SAMPLES:
        raise EvalConfigError(f"bootstrap samples must be within 0-{MAX_BOOTSTRAP_SAMPLES}")
    if seed < 0:
        raise EvalConfigError("seed must be a non-negative integer")
    if not 0.0 < confidence < 1.0:
        raise EvalConfigError("confidence must be within (0, 1)")

    def score(name: str, responses: Mapping[str, str], source: str) -> ConfigResult:
        return score_configuration(
            name,
            dataset,
            responses,
            source=source,
            bootstrap_samples=bootstrap_samples,
            seed=seed,
            confidence=confidence,
        )

    results = [
        score(source.label, load_responses(source.path, dataset), str(source.path))
        for source in sources
    ]
    generated: dict[str, dict[str, str]] = {}
    if generate_offline:
        generated[label] = await generate_responses(dataset, agent)
        results.append(score(label, generated[label], OFFLINE_SOURCE))
    return EvalRun(
        dataset=dataset,
        configurations=tuple(results),
        bootstrap_samples=bootstrap_samples,
        seed=seed,
        confidence=confidence,
        generated_at=datetime.now(timezone.utc),
        generated_responses=generated or None,
    )
