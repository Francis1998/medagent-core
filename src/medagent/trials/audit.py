"""Durable, de-identified audit trail for ``POST /trials/eligibility``.

One ``screening`` row per call and one ``trial`` row per trial screened are
written to the ``trial_screening_audit`` table of the audit database
(``DATABASE_URL``, next to ``audit_log`` and ``cds_hooks_audit``), following the
CDS Hooks convention: HMAC-SHA256 hashes (``PII_HASH_SALT``), a server-generated
screening id, trial and criterion ids, statuses and counts only. No clinical
text, code, value, date of birth or FHIR data is ever stored. MCP calls keep
using the MCP server's JSONL audit log. RESEARCH USE ONLY.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from datetime import datetime, timezone
from typing import Any

import sqlalchemy as sa
from sqlalchemy.ext.asyncio import AsyncEngine

from medagent.agent.audit import get_engine, metadata
from medagent.logging_config import get_logger

logger = get_logger(__name__)


def _utc_now() -> datetime:
    """Current UTC time as a naive datetime, matching the other audit tables."""
    return datetime.now(timezone.utc).replace(tzinfo=None)


trial_screening_audit_table = sa.Table(
    "trial_screening_audit",
    metadata,
    sa.Column("id", sa.Integer, primary_key=True, autoincrement=True),
    # "screening" or "trial"
    sa.Column("event", sa.String(16), nullable=False, index=True),
    # uuid4 generated by the service; links a screening row to its trial rows
    sa.Column("screening_id", sa.String(36), nullable=False, index=True),
    # HMAC-SHA256 of the canonical request (same scheme as the MCP audit log)
    sa.Column("inputs_hash", sa.String(64), nullable=True),
    sa.Column("patient_id_hash", sa.String(64), nullable=True),
    sa.Column("patient_ref_hash", sa.String(64), nullable=True),
    sa.Column("as_of", sa.String(10), nullable=True),
    sa.Column("trial_count", sa.Integer, nullable=True),
    sa.Column("trial_id", sa.String(64), nullable=True),
    sa.Column("trial_version", sa.String(32), nullable=True),
    # potentially_eligible | needs_review | likely_ineligible
    sa.Column("status", sa.String(24), nullable=True),
    sa.Column("trial_rank", sa.Integer, nullable=True),
    sa.Column("met_count", sa.Integer, nullable=True),
    sa.Column("not_met_count", sa.Integer, nullable=True),
    sa.Column("insufficient_count", sa.Integer, nullable=True),
    sa.Column("review_count", sa.Integer, nullable=True),
    # Comma-separated criterion ids that block the trial, exclusions first
    sa.Column("blocking_criteria", sa.Text, nullable=True),
    sa.Column("created_at", sa.DateTime, nullable=False, default=_utc_now),
)

TRIAL_SCREENING_AUDIT_COLUMNS: tuple[str, ...] = tuple(
    column.name
    for column in trial_screening_audit_table.columns
    if column.name not in {"id", "created_at"}
)

# The table is created with the other audit tables on first engine use; this also
# covers an engine initialised before this module was imported.
_ensured_engines: set[int] = set()


async def _ensure_table(engine: AsyncEngine) -> None:
    if id(engine) in _ensured_engines:
        return
    async with engine.begin() as connection:
        await connection.run_sync(trial_screening_audit_table.create, checkfirst=True)
    _ensured_engines.add(id(engine))


async def persist_trial_screening_events(rows: Sequence[Mapping[str, Any]]) -> None:
    """Append trial-screening audit rows in one transaction.

    Only keys naming a ``trial_screening_audit`` column are written, so a caller
    cannot add free text by accident.

    Args:
        rows: Rows built by ``TrialScreening.audit_events`` (``event`` and
            ``screening_id`` are required).
    """
    if not rows:
        return
    engine = await get_engine()
    await _ensure_table(engine)
    created_at = _utc_now()
    values = [
        {
            "created_at": created_at,
            **{column: row.get(column) for column in TRIAL_SCREENING_AUDIT_COLUMNS},
        }
        for row in rows
    ]
    async with engine.begin() as connection:
        await connection.execute(trial_screening_audit_table.insert(), values)
    logger.info("trial_screening_audit_persisted", events=len(values))


async def fetch_trial_screening_events(
    *, screening_id: str | None = None, limit: int = 100
) -> list[dict[str, Any]]:
    """Return trial-screening audit rows in insertion order.

    Args:
        screening_id: Only rows for this screening.
        limit: Maximum number of rows to return.

    Returns:
        List of row dicts.
    """
    engine = await get_engine()
    await _ensure_table(engine)
    query = (
        sa.select(trial_screening_audit_table)
        .order_by(trial_screening_audit_table.c.id)
        .limit(limit)
    )
    if screening_id is not None:
        query = query.where(trial_screening_audit_table.c.screening_id == screening_id)
    async with engine.connect() as connection:
        result = await connection.execute(query)
        return [dict(row) for row in result.mappings().all()]
